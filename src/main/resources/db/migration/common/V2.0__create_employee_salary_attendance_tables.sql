-- ============================================
-- PURCHASE HEADER
-- ============================================

CREATE TABLE PURCHASE (
PURCHASE_ID BIGSERIAL PRIMARY KEY,
PURCHASE_NUMBER VARCHAR(50) NOT NULL UNIQUE,
PROJECT_ID BIGINT NOT NULL,
SUPPLIER_ID BIGINT NOT NULL,
PURCHASE_DATE VARCHAR(15) NOT NULL,

INVOICE_NUMBER VARCHAR(100),
TOTAL_AMOUNT NUMERIC(18,2) DEFAULT 0,
PAID_AMOUNT NUMERIC(18,2) DEFAULT 0,
BALANCE_AMOUNT NUMERIC(18,2) DEFAULT 0,
PAYMENT_STATUS VARCHAR(20)
CHECK (PAYMENT_STATUS IN ('PENDING','PARTIAL','PAID')),
REMARKS TEXT,

CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

CONSTRAINT FK_PURCHASE_SUPPLIER
FOREIGN KEY (SUPPLIER_ID)
REFERENCES SUPPLIER(SUPPLIER_ID)

);

CREATE INDEX IDX_PURCHASE_PROJECT
ON PURCHASE(PROJECT_ID);

CREATE INDEX IDX_PURCHASE_SUPPLIER
ON PURCHASE(SUPPLIER_ID);

-- ============================================
-- PURCHASE DETAILS
-- ============================================

CREATE TABLE PURCHASE_DETAILS (
PURCHASE_DETAILS_ID BIGSERIAL PRIMARY KEY,
PURCHASE_ID BIGINT NOT NULL,
MATERIAL_ID BIGINT NOT NULL,
QUANTITY NUMERIC(18,2) NOT NULL,
RATE NUMERIC(18,2) NOT NULL,
AMOUNT NUMERIC(18,2) NOT NULL,

CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

CONSTRAINT FK_PURCHASE_DETAILS_PURCHASE
FOREIGN KEY (PURCHASE_ID)
REFERENCES PURCHASE(PURCHASE_ID)
ON DELETE CASCADE,

CONSTRAINT FK_PURCHASE_DETAILS_MATERIAL
FOREIGN KEY (MATERIAL_ID)
REFERENCES MATERIAL_MASTER(MATERIAL_ID)

);

CREATE INDEX IDX_PURCHASE_DETAILS_PURCHASE
ON PURCHASE_DETAILS(PURCHASE_ID);

-- ============================================
-- PROJECT EXPENSE
-- ============================================

CREATE TABLE PROJECT_EXPENSE (
PROJECT_EXPENSE_ID BIGSERIAL PRIMARY KEY,
PROJECT_ID BIGINT NOT NULL,
EXPENSE_ID BIGINT NOT NULL,
VENDOR_ID BIGINT,
EXPENSE_DATE VARCHAR(15) NOT NULL,
AMOUNT NUMERIC(18,2) NOT NULL,
PAID_AMOUNT NUMERIC(18,2) DEFAULT 0,
BALANCE_AMOUNT NUMERIC(18,2) NOT NULL,
PAYMENT_STATUS VARCHAR(20)
CHECK (PAYMENT_STATUS IN ('PENDING','PARTIAL','PAID')),
DESCRIPTION TEXT,

CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PROJECT_EXPENSE_PROJECT
    FOREIGN KEY (PROJECT_ID)
    REFERENCES PROJECT(PROJECT_ID),

    CONSTRAINT FK_PROJECT_EXPENSE_EXPENSE
    FOREIGN KEY (EXPENSE_ID)
    REFERENCES EXPENSE_MASTER(EXPENSE_ID),

    CONSTRAINT FK_PROJECT_EXPENSE_VENDOR
    FOREIGN KEY (VENDOR_ID)
    REFERENCES VENDOR(VENDOR_ID)

);

CREATE INDEX IDX_PROJECT_EXPENSE_PROJECT
ON PROJECT_EXPENSE(PROJECT_ID);

CREATE INDEX IDX_PROJECT_EXPENSE_VENDOR
ON PROJECT_EXPENSE(VENDOR_ID);

-- ============================================
-- PAYROLL
