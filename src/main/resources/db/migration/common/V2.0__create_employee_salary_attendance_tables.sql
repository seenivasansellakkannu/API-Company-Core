-- ============================================
-- PAYMENT
-- ============================================

CREATE TABLE PAYMENT (
    PAYMENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PAYMENT_NUMBER VARCHAR(30) UNIQUE NOT NULL,
    PAYMENT_TYPE VARCHAR(30) NOT NULL
    CHECK (
        PAYMENT_TYPE IN (
            'CLIENT_RECEIPT',
            'SUPPLIER_PAYMENT',
            'VENDOR_PAYMENT',
            'EMPLOYEE_PAYMENT'
        )
    ),
    PROJECT_EXPENSE_ID BIGINT,
    PROJECT_ID BIGINT,
    CLIENT_NAME VARCHAR(100),
    SUPPLIER_ID BIGINT,
    VENDOR_ID BIGINT,
    PURCHASE_ID BIGINT,
    PAYROLL_ID BIGINT,
    PAYMENT_DATE DATE NOT NULL,
    PAYMENT_MODE VARCHAR(30),
    REFERENCE_NUMBER VARCHAR(100),
    AMOUNT DECIMAL(18,2) NOT NULL,
    REMARKS VARCHAR(500),

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PAYMENT_PROJECT
    FOREIGN KEY (PROJECT_ID)
    REFERENCES PROJECT(PROJECT_ID),

    CONSTRAINT FK_PAYMENT_PROJECT_EXPENSE
    FOREIGN KEY (PROJECT_EXPENSE_ID)
    REFERENCES PROJECT_EXPENSE(PROJECT_EXPENSE_ID),

    CONSTRAINT FK_PAYMENT_SUPPLIER
    FOREIGN KEY (SUPPLIER_ID)
    REFERENCES SUPPLIER(SUPPLIER_ID),

    CONSTRAINT FK_PAYMENT_VENDOR
    FOREIGN KEY (VENDOR_ID)
    REFERENCES VENDOR(VENDOR_ID)
);

CREATE INDEX IDX_PAYMENT_PURCHASE
ON PAYMENT(PURCHASE_ID);

CREATE INDEX IDX_PAYMENT_EXPENSE
ON PAYMENT(PROJECT_EXPENSE_ID);

