-- ADDRESS
CREATE TABLE ADDRESS (
    ADDRESS_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADDRESS_TYPE VARCHAR(30) NOT NULL,
    ADDRESS_LINE1 VARCHAR(150) NOT NULL,
    ADDRESS_LINE2 VARCHAR(150),
    CITY VARCHAR(80) NOT NULL,
    THALUK VARCHAR(80),
    ADD_STATE VARCHAR(80) NOT NULL,
    COUNTRY VARCHAR(80) NOT NULL,
    PINCODE VARCHAR(10) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- EMPLOYEE
CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR(50) NOT NULL,
    EMPLOYEE_LEVEL VARCHAR(10) NOT NULL,
    ADDRESS_ID BIGINT,

    PRIMARY_PHONE_NUMBER VARCHAR(15) NOT NULL,
    SECONDARY_PHONE_NUMBER VARCHAR(15),

    DATE_OF_JOINING VARCHAR(15) NOT NULL,
    DATE_OF_RESIGN VARCHAR(15),

    EMPLOYEE_STATUS VARCHAR(20),
    EMAIL VARCHAR(100) UNIQUE,

    CONSTRAINT FK_EMPLOYEE_ADDRESS
    FOREIGN KEY (ADDRESS_ID)
    REFERENCES ADDRESS(ADDRESS_ID)
    ON DELETE SET NULL
);

-- SALARY
CREATE TABLE SALARY (
    EMPLOYEE_ID BIGINT PRIMARY KEY,
    EMPLOYEE_LEVEL VARCHAR(10) NOT NULL,
    SALARY_PER_HOUR DECIMAL(10,2) NOT NULL,

    CONSTRAINT FK_SALARY_EMPLOYEE
    FOREIGN KEY (EMPLOYEE_ID)
    REFERENCES EMPLOYEE(EMPLOYEE_ID)
    ON DELETE CASCADE
);

-- PROJECT
CREATE TABLE PROJECT (
    PROJECT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_CODE VARCHAR(20) UNIQUE NOT NULL,
    PROJECT_NAME VARCHAR(100) NOT NULL,
    ADDRESS_ID BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PROJECT_ADDRESS
    FOREIGN KEY (ADDRESS_ID)
    REFERENCES ADDRESS(ADDRESS_ID)
    ON DELETE SET NULL
);

-- ATTENDANCE
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    EMPLOYEE_ID BIGINT NOT NULL,
    PROJECT_ID BIGINT NOT NULL,

    WORK_DATE VARCHAR(15) NOT NULL,

    WORKDAYS DECIMAL(10,2) NOT NULL,

    CONSTRAINT UQ_ATTENDANCE
    UNIQUE (EMPLOYEE_ID, PROJECT_ID, WORK_DATE),

    CONSTRAINT FK_ATTENDANCE_EMPLOYEE
    FOREIGN KEY (EMPLOYEE_ID)
    REFERENCES EMPLOYEE(EMPLOYEE_ID)
    ON DELETE CASCADE,

    CONSTRAINT FK_ATTENDANCE_PROJECT
    FOREIGN KEY (PROJECT_ID)
    REFERENCES PROJECT(PROJECT_ID)
    ON DELETE CASCADE
);

CREATE INDEX IDX_ATTENDANCE_EMPLOYEE_ID
ON ATTENDANCE(EMPLOYEE_ID);